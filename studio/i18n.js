let language;
try { language = localStorage.getItem('ams-language'); } catch { /* Browser storage is optional. */ }
if (!['ru','en'].includes(language)) language = navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
export function t(value, ...values) {
  const tagged = Array.isArray(value), key = tagged ? value.join('{}') : value;
  const text = language === 'en' ? english[key] ?? key : key;
  let index = 0;
  return tagged ? text.replace(/\{\}/g, () => String(values[index++])) : text;
}
export function initializeI18n(beforeReload = () => true) {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const key = node.nodeValue.trim();
    if (Object.hasOwn(english,key)) node.nodeValue = node.nodeValue.replace(key,t(key));
  }
  for (const node of document.querySelectorAll('[aria-label]')) {
    const key = node.getAttribute('aria-label'); if (Object.hasOwn(english,key)) node.setAttribute('aria-label',t(key));
  }
  const selector = document.getElementById('language'); selector.value = language;
  selector.onchange = () => {
    if (!beforeReload()) { selector.value = language; return; }
    language = selector.value;
    try { localStorage.setItem('ams-language',language); } catch { /* Reload uses browser default if storage is blocked. */ }
    // Existing scene drafts already live in sessionStorage. Reload preserves the session URL and draft recovery.
    location.reload();
  };
}
